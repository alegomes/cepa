#!/usr/bin/env python3
"""Derive the plugin list shown to humans from .claude-plugin/marketplace.json.

One place, two consumers, so the list cannot drift from the marketplace:
  - bin/install.sh prints it in its final summary (default mode);
  - docs/getting-started.md carries it between two HTML-comment markers
    (a markdown file cannot derive at read time, so it is generated).

Usage:
  plugin-summary.py [--marketplace PATH]                 terminal lines
  plugin-summary.py [--marketplace PATH] --markdown      markdown bullet list
  plugin-summary.py [--marketplace PATH] --write FILE    rewrite FILE's block
  plugin-summary.py [--marketplace PATH] --check FILE    exit 1 if block is stale

The short text of each plugin is the first sentence of its `description`;
when that exceeds WIDTH it is cut at the first clause break (colon, dash,
parenthesis, comma) and, failing that, at a word boundary. marketplace.json gets no new
field: its schema belongs to Claude Code.
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_MARKETPLACE = REPO / ".claude-plugin" / "marketplace.json"
BEGIN = "<!-- plugins:begin (generated by bin/plugin-summary.py --write; do not edit) -->"
END = "<!-- plugins:end -->"
WIDTH = 72


def short(description, width=WIDTH):
    text = " ".join((description or "").split())
    m = re.search(r"[.!?](\s|$)", text)
    if m:
        text = text[: m.start()]
    if len(text) > width:
        # Too long: keep the head, up to the first clause break.
        cut = re.search(r"(?<=.{12})(: | — | \(|, | \+ )", text)
        if cut:
            text = text[: cut.start()]
    if len(text) > width:
        text = text[: width - 1].rsplit(" ", 1)[0].rstrip(" ,;:-—(") + "…"
    return text


def load(path):
    return [(p["name"], short(p.get("description"))) for p in json.load(open(path))["plugins"]]


def terminal(plugins):
    pad = max(len(n) for n, _ in plugins)
    return "\n".join(f"    {n.ljust(pad)}  — {t}" for n, t in plugins)


def markdown(plugins):
    return "\n".join(f"   - `{n}`: {t}" for n, t in plugins)


def block(plugins):
    return f"   {BEGIN}\n{markdown(plugins)}\n   {END}"


BLOCK_RE = re.compile(r"[ \t]*<!-- plugins:begin.*?-->\n(?:.*?\n)?[ \t]*<!-- plugins:end -->", re.S)


def rewrite(text, plugins):
    if not BLOCK_RE.search(text):
        raise SystemExit("markers `plugins:begin` / `plugins:end` not found")
    return BLOCK_RE.sub(lambda _: block(plugins), text, count=1)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--marketplace", default=str(DEFAULT_MARKETPLACE))
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--markdown", action="store_true")
    mode.add_argument("--write", metavar="FILE")
    mode.add_argument("--check", metavar="FILE")
    a = ap.parse_args()
    plugins = load(a.marketplace)
    if a.write:
        p = Path(a.write)
        p.write_text(rewrite(p.read_text(), plugins))
    elif a.check:
        text = Path(a.check).read_text()
        if rewrite(text, plugins) != text:
            print(f"{a.check}: plugin block is out of sync with {a.marketplace}; "
                  f"run bin/plugin-summary.py --write {a.check}", file=sys.stderr)
            return 1
    elif a.markdown:
        print(markdown(plugins))
    else:
        print(terminal(plugins))
    return 0


if __name__ == "__main__":
    sys.exit(main())
